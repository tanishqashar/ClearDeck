// Runs the production frontend against the real Express API and a NEW temporary SQLite file.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'taskboard-browser-'));
process.env.DB_PATH = path.join(dir, 'browser.db');
process.env.JWT_SECRET = 'browser-test-only-secret';
const express = require('express');
const app = require('../server/server');
let backend, frontend, browser, page;
const shots = path.resolve(__dirname, '../docs/screenshots');
fs.mkdirSync(shots, { recursive: true });
async function start(app, port) {
    const server = app.listen(port, '127.0.0.1');
    await new Promise((resolve,reject) => { server.once('listening',resolve);server.once('error',reject); });
    return server;
}
