    const elapsed=performance.now()-started;
    assert.ok(elapsed<2000,`100-task board browser load took ${elapsed.toFixed(1)}ms`);
    console.log(`100+ task board browser open to rendered cards: ${elapsed.toFixed(1)}ms`);
