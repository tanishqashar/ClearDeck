    // Real browser timing for a board with 100+ tasks (not just API response time).
    const token = await page.evaluate(()=>localStorage.getItem('token'));
    const call = async (route, method='GET', body) => {
        const response=await fetch(`http://127.0.0.1:${backendPort}/api${route}`,{method,headers:{Authorization:`Bearer ${token}`,'Content-Type':'application/json'},...(body ? {body:JSON.stringify(body)} : {})});
        assert.ok(response.ok, route);return response.json();
    };
    const boardInfo=(await call('/boards'))[0];
    const liveBoard=await call(`/boards/${boardInfo.id}`);
    const colId=liveBoard.columns[0].id;
    for(let i=0;i<100;i++) await call(`/boards/${boardInfo.id}/tasks`,'POST',{title:`Performance card ${i}`,column_id:colId});
    const injection='<img src=x onerror="window.taskboardInjected=true">';
    await call(`/boards/${boardInfo.id}/tasks`,'POST',{title:injection,column_id:colId});
    await page.getByRole('button',{name:'Back to boards',exact:true}).click();
    await page.getByRole('button',{name:'Open',exact:true}).waitFor();
    const started=performance.now();
