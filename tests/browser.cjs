    const backendPort = backend.address().port;
    const ui = express(); ui.use(express.static(path.resolve(__dirname, '../build')));
    frontend = await start(ui, 0);
    const frontendPort = frontend.address().port;
    browser = await chromium.launch({ headless:true, ...(process.env.CHROMIUM_EXECUTABLE ? {executablePath:process.env.CHROMIUM_EXECUTABLE} : {}), args:['--no-sandbox','--disable-dev-shm-usage'] });
    page = await browser.newPage({ viewport:{width:1440,height:1000} });
    page.setDefaultTimeout(10000);
    await page.route('**/api/**', route => route.continue({
        url: route.request().url().replace('http://localhost:5000', `http://127.0.0.1:${backendPort}`)
    }));
    page.on('response', async r => { if (r.url().includes('/api/') && r.status() >= 400) console.log('API error:',r.status(),new URL(r.url()).pathname,await r.text()); });
