    await taskDialog.getByLabel('Description',{exact:true}).fill('Searchable description');
    await taskDialog.getByLabel('Priority',{exact:true}).selectOption('High');
    const futureDate = new Date(Date.now() + 2 * 24 * 60 * 60 * 1000).toISOString().slice(0, 10);
    await taskDialog.getByLabel('Due date',{exact:true}).fill(futureDate);
    const memberOption = await taskDialog.getByLabel('Assignee',{exact:true}).locator('option').filter({hasText:'Browser Member'}).getAttribute('value');
    await taskDialog.getByLabel('Assignee',{exact:true}).selectOption(memberOption);
    await taskDialog.getByRole('button',{name:'Save task',exact:true}).click();
    await card('Edited task').waitFor();
