    await page.screenshot({path:path.join(shots,'dashboard.png'),fullPage:true,animations:'disabled'});
    await page.getByRole('button',{name:'Open',exact:true}).click();
    await page.getByRole('region',{name:'Column To Do',exact:true}).waitFor();
