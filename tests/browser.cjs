    await page.getByRole('button',{name:'Add member',exact:true}).click();
    await page.getByText('Browser Member (member)',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Close',exact:true}).click();
    const region = name => page.getByRole('region',{name:`Column ${name}`,exact:true});
    const card = title => page.locator('.MuiCard-root').filter({has:page.getByRole('heading',{name:title,exact:true})});
