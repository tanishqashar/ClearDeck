    await page.getByRole('button',{name:'Back to boards',exact:true}).click();
    await page.getByRole('button',{name:'Rename',exact:true}).click();
    assert.equal(await page.getByLabel('Board description',{exact:true}).inputValue(),'End-to-end verified college project');
    await page.getByLabel('Board Name',{exact:true}).fill('Renamed submission');
